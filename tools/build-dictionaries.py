"""Builds pii-guard's dictionary modules from public-domain sources.

Run from the repo root:  python -I tools/build-dictionaries.py
Writes pii-guard/hooks/data/*.ts. Network access is needed once; the generated
files are committed so users never download anything.

Sources (all US-government public domain, or free for any use):
  first names  SSA baby names, https://www.ssa.gov/oact/babynames/names.zip
  surnames     US Census 2010, https://www2.census.gov/topics/genealogy/2010surnames/names.zip
  common words google-10000-english (Google Trillion Word corpus derived), GitHub first20hours
  conditions   CMS ICD-10-CM code descriptions (3-character categories), cms.gov
  drugs        FDA Drugs@FDA Products.txt, https://www.fda.gov/media/89850/download
"""
from __future__ import annotations

import csv
import io
import json
import os
import re
import sys
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'pii-guard', 'hooks', 'data')
os.makedirs(OUT, exist_ok=True)
UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) pii-guard-dictionary-builder/1.0'}


def fetch(url: str) -> bytes:
    """Downloads with TLS verification on. If Python's trust store rejects the chain
    (a local inspection proxy, say), PowerShell's Invoke-WebRequest is tried, which
    verifies against the Windows certificate store instead. Verification is never disabled."""
    req = urllib.request.Request(url, headers=UA)
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.read()
    except Exception as err:  # noqa: BLE001
        if ('CERTIFICATE_VERIFY_FAILED' not in str(err) and '403' not in str(err)) or os.name != 'nt':
            raise
        import subprocess, tempfile
        tmp = tempfile.NamedTemporaryFile(delete=False, suffix='.bin'); tmp.close()
        cmd = ['powershell', '-NoProfile', '-NonInteractive', '-Command',
               f"$ProgressPreference='SilentlyContinue'; Invoke-WebRequest -Uri '{url}' -OutFile '{tmp.name}' -UseBasicParsing -UserAgent '{UA['User-Agent']}'"]
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
        if r.returncode != 0:
            raise RuntimeError(f'powershell download failed: {r.stderr.strip()[:200]}') from err
        with open(tmp.name, 'rb') as fh:
            data = fh.read()
        os.unlink(tmp.name)
        return data


def write_ts(name: str, const: str, words: list[str], note: str) -> None:
    words = sorted(set(w for w in words if w))
    path = os.path.join(OUT, f'{name}.ts')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(f'// Generated by tools/build-dictionaries.py. {note}\n')
        fh.write(f'// {len(words)} entries, lower-case. Do not edit by hand.\n')
        fh.write(f'export const {const}: readonly string[] = ')
        fh.write(json.dumps(words, ensure_ascii=False, separators=(',', ':')))
        fh.write('\n')
    print(f'{name}: {len(words)} entries -> {os.path.relpath(path, ROOT)}')


WORD = re.compile(r"^[a-z][a-z'-]+$")


def first_names(limit: int = 5000) -> list[str]:
    try:
        data = fetch('https://www.ssa.gov/oact/babynames/names.zip')
    except Exception as err:  # noqa: BLE001
        # SSA refuses some clients; fall back to Hadley Wickham's mirror of the SSA top-1000 per year.
        print(f'  first names: SSA failed ({err}); using the hadley/data-baby-names mirror', file=sys.stderr)
        url = 'https://raw.githubusercontent.com/hadley/data-baby-names/master/baby-names.csv'
        counts: dict[str, float] = {}
        for row in csv.DictReader(io.StringIO(fetch(url).decode('utf-8', 'ignore'))):
            if int(row['year']) < 1940:
                continue
            n = row['name'].strip().lower()
            counts[n] = counts.get(n, 0.0) + float(row['percent'])
        ranked = sorted(counts.items(), key=lambda kv: -kv[1])
        return [n for n, _ in ranked[:limit] if WORD.match(n) and len(n) >= 3]
    z = zipfile.ZipFile(io.BytesIO(data))
    counts: dict[str, int] = {}
    for info in z.infolist():
        if not info.filename.startswith('yob') or not info.filename.endswith('.txt'):
            continue
        year = int(info.filename[3:7])
        if year < 1940:
            continue
        for line in z.read(info).decode('utf-8', 'ignore').splitlines():
            name, _sex, n = line.strip().split(',')
            counts[name.lower()] = counts.get(name.lower(), 0) + int(n)
    ranked = sorted(counts.items(), key=lambda kv: -kv[1])
    return [n for n, _ in ranked[:limit] if WORD.match(n) and len(n) >= 3]


def surnames(limit: int = 10000) -> list[str]:
    z = zipfile.ZipFile(io.BytesIO(fetch('https://www2.census.gov/topics/genealogy/2010surnames/names.zip')))
    csv_name = next(n for n in z.namelist() if n.lower().endswith('.csv'))
    rows = csv.DictReader(io.TextIOWrapper(z.open(csv_name), encoding='utf-8', errors='ignore'))
    out: list[str] = []
    for row in rows:
        name = (row.get('name') or '').strip().lower()
        if name and name != 'all other names' and WORD.match(name) and len(name) >= 3:
            out.append(name)
        if len(out) >= limit:
            break
    return out


def common_words() -> list[str]:
    url = 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa.txt'
    return [w.strip().lower() for w in fetch(url).decode('utf-8').splitlines() if w.strip()]


GENERIC_CONDITION = re.compile(
    r'^(other|unspecified|certain|personal history|family history|encounter|contact with|exposure to|'
    r'problems related|persons|screening|observation|examination|follow-up|aftercare|complications|'
    r'injury|fracture|open wound|superficial|burn|corrosion|poisoning|adverse effect|toxic effect|'
    r'sequelae|symptoms|signs|abnormal|findings|z\d|codes for special purposes)',
    re.I,
)


def conditions() -> list[str]:
    common = set(common_words())
    candidates = [
        'https://www.cms.gov/files/zip/2026-code-descriptions-tabular-order.zip',
        'https://www.cms.gov/files/zip/2025-code-descriptions-tabular-order.zip',
        'https://www.cms.gov/files/zip/2024-code-descriptions-tabular-order.zip',
    ]
    data = None
    for url in candidates:
        try:
            data = fetch(url)
            break
        except Exception as err:  # noqa: BLE001
            print(f'  conditions: {url} failed ({err}); trying next', file=sys.stderr)
    if data is None:
        raise RuntimeError('no ICD-10-CM description zip could be fetched')
    z = zipfile.ZipFile(io.BytesIO(data))
    # The "order" file lists every code and category, fixed width:
    # order(5) code(7) header-flag(1) short(60) long(...). Categories are the 3-character codes.
    name = next(n for n in z.namelist() if 'order' in n.lower() and n.lower().endswith('.txt') and 'addenda' not in n.lower())
    out: set[str] = set()
    for line in z.read(name).decode('utf-8', 'ignore').splitlines():
        if len(line) < 78:
            continue
        code = line[6:13].strip()
        desc = line[77:].strip()
        if len(code) != 3:
            continue
        if GENERIC_CONDITION.match(desc):
            continue
        desc = re.sub(r'\s*\[.*?\]', '', desc)          # drop bracketed synonyms
        desc = desc.split(',')[0].split(' due to ')[0].split(' with ')[0].split(' without ')[0].strip()
        desc = re.sub(r'\s+NOS$', '', desc)
        if GENERIC_CONDITION.match(desc):
            continue
        if len(desc) < 5 or len(desc.split()) > 5:
            continue
        # A single ordinary English word ("contact", "absent", "pain") is not a condition on its own.
        if len(desc.split()) == 1 and desc.lower() in common:
            continue
        out.add(desc.lower())
    # A few very common spellings the category titles phrase differently.
    out.update(["crohn's disease", 'crohns disease', 'ulcerative colitis', 'type 1 diabetes', 'type 2 diabetes',
                'heart attack', 'stroke', 'depression', 'anxiety disorder', 'adhd', 'autism', 'asthma', 'eczema',
                'psoriasis', 'migraine', 'epilepsy', 'dementia', "alzheimer's disease", "parkinson's disease",
                'multiple sclerosis', 'hiv', 'aids', 'hepatitis', 'tuberculosis', 'covid-19', 'long covid',
                'breast cancer', 'prostate cancer', 'lung cancer', 'bowel cancer', 'skin cancer', 'leukaemia', 'leukemia',
                'lymphoma', 'miscarriage', 'abortion', 'pregnancy', 'ivf', 'infertility', 'menopause',
                'bipolar disorder', 'schizophrenia', 'ptsd', 'ocd', 'eating disorder', 'anorexia', 'bulimia',
                'self-harm', 'suicide attempt', 'overdose', 'alcoholism', 'drug addiction', 'gender dysphoria'])
    return sorted(out)


def drugs(limit: int = 2500) -> list[str]:
    z = zipfile.ZipFile(io.BytesIO(fetch('https://www.fda.gov/media/89850/download')))
    name = next(n for n in z.namelist() if n.lower().endswith('products.txt'))
    text = z.read(name).decode('utf-8', 'ignore')
    reader = csv.DictReader(io.StringIO(text), delimiter='\t')
    counts: dict[str, int] = {}
    for row in reader:
        for key in ('DrugName', 'ActiveIngredient'):
            raw = (row.get(key) or '').strip().lower()
            for part in re.split(r'[;,/]| and ', raw):
                part = re.sub(r'\(.*?\)', '', part).strip()
                part = re.sub(r'\b(hydrochloride|sodium|potassium|acetate|sulfate|sulphate|tartrate|maleate|citrate|mesylate|phosphate|succinate|besylate|calcium|magnesium|dihydrate|monohydrate|hcl)\b', '', part).strip()
                if 4 <= len(part) <= 30 and re.match(r"^[a-z][a-z0-9 '-]+$", part):
                    counts[part] = counts.get(part, 0) + 1
    ranked = sorted(counts.items(), key=lambda kv: -kv[1])
    return [d for d, _ in ranked[:limit]]


if __name__ == '__main__':
    failures = 0
    for label, const, fn, note in [
        ('first-names', 'FIRST_NAMES', first_names, 'Source: SSA baby names (US public domain), 1940 onwards, top 5000.'),
        ('surnames', 'SURNAMES', surnames, 'Source: US Census 2010 surnames (US public domain), top 10000.'),
        ('common-words', 'COMMON_WORDS', common_words, 'Source: google-10000-english (first20hours), free for any use.'),
        ('conditions', 'CONDITIONS', conditions, 'Source: CMS ICD-10-CM 3-character category titles (US public domain), plus common lay terms.'),
        ('drugs', 'DRUGS', drugs, 'Source: FDA Drugs@FDA Products.txt (US public domain), brand and ingredient names.'),
    ]:
        try:
            write_ts(label, const, fn(), note)
        except Exception as err:  # noqa: BLE001
            failures += 1
            print(f'{label}: FAILED: {err}', file=sys.stderr)
    sys.exit(1 if failures else 0)
